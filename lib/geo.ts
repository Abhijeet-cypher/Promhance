/**
 * Country detection from edge headers + a small ISO-3166 helper.
 *
 * Detection order:
 *   1. `cf-ipcountry`   — Cloudflare sets this from the real client before it
 *                         reaches the origin (domain is proxied by Cloudflare).
 *   2. `x-vercel-ip-country` — Vercel's own geo header, used as a fallback.
 *   3. `x-country-code` — generic fallback for other proxies/platforms.
 *
 * Cloudflare uses `XX`/`T1` for unknown/Tor, which we treat as "no country".
 */

const INVALID_CODES = new Set(["XX", "T1", "A1", "A2", "O1"]);

/** Returns an uppercase ISO-3166 alpha-2 code from request headers, or null. */
export function getCountryFromRequest(req: Request): string | null {
  const raw =
    req.headers.get("cf-ipcountry") ??
    req.headers.get("x-vercel-ip-country") ??
    req.headers.get("x-country-code");

  if (!raw) return null;

  const code = raw.trim().toUpperCase();
  if (code.length !== 2 || INVALID_CODES.has(code)) return null;
  if (!/^[A-Z]{2}$/.test(code)) return null;

  return code;
}

